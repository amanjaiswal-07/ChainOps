"""
ChainOps HTTP API.

Run:  uvicorn api:app --app-dir src --port 8000
Docs: http://localhost:8000/docs (generated by FastAPI from these models)

Design notes
  * Endpoints are plain `def`, so FastAPI runs each request in its worker
    thread pool. A decision cycle runs inside the request and the response
    contains its final status; nothing is queued in the background.
  * Schema errors return 422 (FastAPI/Pydantic). Business-rule failures
    return 201 with status VALIDATION_FAILED, because they are recorded
    decisions that should be inspectable later.
  * Unexpected errors return a generic 500 body. Stack traces stay in the
    server log and are never sent to the client.
  * There is no authentication. `reviewer` is recorded as given, not
    verified (see README, Known limitations).
"""

import logging
import uuid
from contextlib import asynccontextmanager
from typing import Literal

from fastapi import FastAPI, HTTPException, Query, Request, Response
from fastapi.responses import JSONResponse
from pydantic import BaseModel, ConfigDict, Field

import config
import db_init
import governance
import llm_config
import workflow
from db_service import list_products
from events import SupplyChainEvent
from logging_config import setup_logging
from overlay import SnapshotOverlay

log = logging.getLogger("chainops.api")


@asynccontextmanager
async def lifespan(app: FastAPI):
    setup_logging()
    db_init.ensure_database()
    log.info("api_started", extra={"fields": {"llm_mode": llm_config.resolve_mode()}})
    yield


app = FastAPI(
    title="ChainOps API",
    version="1.0.0",
    description="Event-driven multi-agent supply chain decisions with human approval.",
    lifespan=lifespan,
)


# ---------------------------------------------------------------------------
# Request limits and error handling
# ---------------------------------------------------------------------------

@app.middleware("http")
async def limit_body_size(request: Request, call_next):
    """Reject oversized bodies before they are parsed."""
    length = request.headers.get("content-length")
    if length and length.isdigit() and int(length) > config.MAX_REQUEST_BYTES:
        return JSONResponse(status_code=413, content={
            "error": "payload_too_large", "max_bytes": config.MAX_REQUEST_BYTES})
    return await call_next(request)


@app.exception_handler(governance.DecisionNotFound)
async def _not_found(request: Request, exc: governance.DecisionNotFound):
    return JSONResponse(status_code=404, content={"error": "decision_not_found", "decision_id": str(exc)})


@app.exception_handler(governance.InvalidTransition)
async def _invalid_transition(request: Request, exc: governance.InvalidTransition):
    return JSONResponse(status_code=409, content={
        "error": "invalid_transition", "decision_id": exc.decision_id,
        "current_status": exc.current, "attempted": exc.attempted, "message": str(exc)})


@app.exception_handler(llm_config.LLMConfigError)
async def _llm_config(request: Request, exc: llm_config.LLMConfigError):
    return JSONResponse(status_code=503, content={"error": "llm_not_configured", "message": str(exc)})


@app.exception_handler(Exception)
async def _unexpected(request: Request, exc: Exception):
    error_id = uuid.uuid4().hex[:8]
    log.exception("unhandled_error", extra={"fields": {"error_id": error_id, "path": request.url.path}})
    return JSONResponse(status_code=500, content={"error": "internal_error", "error_id": error_id})


# ---------------------------------------------------------------------------
# Request / response models
# ---------------------------------------------------------------------------

class DecisionCycleRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    product_id: int = Field(..., gt=0)
    overlay: SnapshotOverlay | None = Field(
        None, description="Optional what-if changes. A cycle with an overlay is a scenario and always runs as a dry run.")
    dry_run: bool = Field(False, description="If true, an approved decision is recorded but no purchase order is written.")


class ReviewRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    reviewer: str = Field(..., min_length=1, max_length=64, description="Name of the person deciding (not verified)")
    note: str | None = Field(None, max_length=500)


class RecommendedAction(BaseModel):
    decision_type: Literal["REORDER", "HOLD"]
    supplier_id: int | None
    quantity: int
    expedite: bool


class DecisionSummary(BaseModel):
    decision_id: str
    status: str
    trigger: str
    event_type: str | None
    product_id: int | None
    validation_status: str | None
    risk_level: str | None
    risk_reasons: list[str] | None
    recommended_action: RecommendedAction | None
    approval_required: bool | None
    execution_result: dict | None
    error: dict | None
    duplicate: bool = False
    trigger_reason: str | None = None
    links: dict


def _summary(record: dict) -> DecisionSummary:
    final = record.get("final_decision")
    action = None
    if final:
        details = final.get("details") or {}
        action = RecommendedAction(decision_type=final["decision_type"], supplier_id=details.get("supplier_id"),
                                   quantity=details.get("quantity") or 0, expedite=bool(details.get("expedite")))
    did = record["decision_id"]
    links = {"self": f"/decisions/{did}"}
    if record["status"] == governance.PENDING_APPROVAL:
        links.update(approve=f"/decisions/{did}/approve", reject=f"/decisions/{did}/reject")
    if record["status"] == governance.EXECUTION_FAILED:
        links["retry"] = f"/decisions/{did}/retry-execution"
    return DecisionSummary(
        decision_id=did, status=record["status"], trigger=record["trigger"], event_type=record.get("event_type"),
        product_id=record.get("product_id"), validation_status=record.get("validation_status"),
        risk_level=record.get("risk_level"), risk_reasons=record.get("risk_reasons"),
        recommended_action=action, approval_required=record.get("approval_required"),
        execution_result=record.get("execution_result"), error=record.get("error"),
        duplicate=record.get("duplicate", False), trigger_reason=record.get("trigger_reason"), links=links)


