@app.get("/health")
def health():
    """Liveness plus the facts an operator needs: LLM mode and DB reachability."""
    products = list_products()
    return {"status": "ok", "llm_mode": llm_config.resolve_mode(), "products": len(products)}


@app.get("/products")
def products():
    return list_products()


@app.post("/events", response_model=DecisionSummary, status_code=201,
          responses={200: {"description": "Duplicate event_id: the original decision is returned"}})
def post_event(event: SupplyChainEvent, response: Response):
    """
    Receive a business event (webhook). Runs a decision cycle if the event
    crosses its trigger threshold. Re-sending an event_id returns the
    original decision with `duplicate: true` and HTTP 200.
    """
    record = workflow.process_event(event)
    if record.get("duplicate"):
        response.status_code = 200
    return _summary(record)


@app.post("/decision-cycles", response_model=DecisionSummary, status_code=201)
def post_decision_cycle(request: DecisionCycleRequest):
    """Run one cycle on demand (MANUAL), or a what-if SCENARIO if an overlay is given."""
    if request.product_id not in {p["id"] for p in list_products()}:
        raise HTTPException(status_code=404, detail=f"product {request.product_id} not found")
    has_overlay = request.overlay is not None and not request.overlay.is_empty()
    record = workflow.run_cycle(
        request.product_id,
        trigger="SCENARIO" if has_overlay else "MANUAL",
        overlay=request.overlay if has_overlay else None,
        dry_run=request.dry_run or has_overlay,  # what-if data never writes a real PO
    )
    return _summary(record)


@app.get("/decisions", response_model=list[DecisionSummary])
def get_decisions(status: str | None = None, limit: int = Query(50, ge=1, le=200)):
    return [_summary(r) for r in governance.list_records(limit=limit, status=status)]


@app.get("/decisions/{decision_id}")
def get_decision(decision_id: str):
    """Full audit record: input, validation report, agent trace and outputs, risk reasons, review, execution."""
    return governance.get_record(decision_id)


@app.post("/decisions/{decision_id}/approve", response_model=DecisionSummary)
def approve_decision(decision_id: str, review: ReviewRequest):
    """PENDING_APPROVAL -> APPROVED -> executed. 409 from any other status."""
    return _summary(governance.approve(decision_id, review.reviewer, review.note))


@app.post("/decisions/{decision_id}/reject", response_model=DecisionSummary)
def reject_decision(decision_id: str, review: ReviewRequest):
    """PENDING_APPROVAL -> REJECTED. A rejected decision never executes. 409 from any other status."""
    return _summary(governance.reject(decision_id, review.reviewer, review.note))


@app.post("/decisions/{decision_id}/retry-execution", response_model=DecisionSummary)
def retry_decision(decision_id: str):
    """Retry a decision whose execution failed. 409 from any other status."""
    return _summary(governance.retry_execution(decision_id))
